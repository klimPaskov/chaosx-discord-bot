#!/usr/bin/env python3
"""Write one troubleshooting note per tooling repo, straight from its source.

Docs explain intent; source explains behaviour. This walks each indexed tooling repo, pulls out the install paths,
config locations and environment variables the code actually looks for, and writes a short note into the vault's
Tooling folder. Those notes are indexed, so "why does it say X is not installed" has a page that lists the exact
paths the app checks — which is what a changelog can never answer.
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from chaosx_bot.config import load_settings  # noqa: E402
from chaosx_bot.indexer import CODE_SUFFIXES, TOOLING_SKIP_DIRS, parse_extra_roots  # noqa: E402

PATH_RE = re.compile(r"[\"'](/(?:Applications|usr|opt|etc|var|Library)[^\"'\n]{2,120})[\"']")
HOME_RE = re.compile(r"[\"'](~/[^\"'\n]{2,100})[\"']")
ENV_RE = re.compile(r"[\"']([A-Z][A-Z0-9_]{3,40})[\"']")
MAX_FILES = 400
MAX_BYTES = 400_000


def source_files(root: Path) -> list[Path]:
    out: list[Path] = []
    for path in root.rglob("*"):
        if len(out) >= MAX_FILES:
            break
        try:
            if not path.is_file() or path.suffix.lower() not in CODE_SUFFIXES:
                continue
            if set(path.relative_to(root).parts) & TOOLING_SKIP_DIRS:
                continue
            if path.stat().st_size > MAX_BYTES:
                continue
        except OSError:
            continue
        out.append(path)
    return out


def readme_of(root: Path) -> str:
    for name in ("README.md", "readme.md", "DEVELOPMENT.md"):
        candidate = root / name
        if candidate.exists():
            try:
                return candidate.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                return ""
    return ""


def scan(root: Path) -> dict[str, Counter]:
    paths: Counter = Counter()
    homes: Counter = Counter()
    envs: Counter = Counter()
    scanned = 0
    for path in source_files(root):
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        scanned += 1
        for match in PATH_RE.finditer(text):
            paths[match.group(1)] += 1
        for match in HOME_RE.finditer(text):
            homes[match.group(1)] += 1
        for match in ENV_RE.finditer(text):
            if match.group(1).startswith(("PATH", "HOME", "USER", "APPDATA")):
                envs[match.group(1)] += 1
    return {"paths": paths, "homes": homes, "envs": envs, "scanned": Counter({"n": scanned})}


def build_note(name: str, root: Path) -> str:
    data = scan(root)
    entries = Path(root).name
    lines = [
        f"# {entries} — how it actually behaves",
        "",
        f"Generated from `{root}` source ({data['scanned']['n']} files). This note exists because a README describes",
        "intent while the code decides behaviour: when the app says something is not installed, these are the paths",
        "and variables it actually looked at.",
        "",
        "## Install and config paths the code checks",
        "",
    ]
    if data["paths"]:
        for value, count in data["paths"].most_common(25):
            lines.append(f"- `{value}`" + (f"  ({count}×)" if count > 1 else ""))
    else:
        lines.append("- (no absolute paths found in source)")
    lines += ["", "## User-level locations", ""]
    if data["homes"]:
        for value, count in data["homes"].most_common(15):
            lines.append(f"- `{value}`")
    else:
        lines.append("- (none)")
    lines += ["", "## Environment variables read", ""]
    if data["envs"]:
        for value, count in data["envs"].most_common(15):
            lines.append(f"- `{value}`")
    else:
        lines.append("- (none)")
    readme = readme_of(root)
    if readme:
        summary = [line.strip() for line in readme.splitlines() if line.strip() and not line.startswith("#")][:6]
        if summary:
            lines += ["", "## What the project says it is", ""]
            lines += [f"> {line}" for line in summary]
    lines += ["", f"_{name} · generated by scripts/build_app_notes.py_", ""]
    return "\n".join(lines)


def main() -> int:
    settings = load_settings()
    roots = parse_extra_roots(settings.extra_knowledge_roots)
    if not roots:
        print("no tooling roots configured")
        return 1
    vault = Path(settings.obsidian_vault_path or "")
    if not vault.exists():
        print(f"vault not found: {vault}")
        return 1
    target = vault / "Tooling"
    target.mkdir(parents=True, exist_ok=True)
    written = 0
    for name, root in roots:
        note = build_note(name, root)
        out = target / f"{root.name} — behaviour from source.md"
        out.write_text(note, encoding="utf-8")
        written += 1
        print(f"wrote {out.name} ({len(note)} chars)")
    print(f"{written} notes in {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
